/** Renders a shortcut like "mod+shift+k" as macOS key symbols. */
export function Kbd({ keys }: { keys: string }): React.JSX.Element {
  const map: Record<string, string> = {
    mod: '⌘',
    shift: '⇧',
    alt: '⌥',
    ctrl: '⌃',
    enter: '↵',
    backspace: '⌫',
    esc: 'Esc',
    up: '↑',
    down: '↓',
    space: 'Space'
  }
  return (
    <span className="kbd">
      {keys.split('+').map((k) => (
        <kbd key={k}>{map[k] ?? k.toUpperCase()}</kbd>
      ))}
    </span>
  )
}
