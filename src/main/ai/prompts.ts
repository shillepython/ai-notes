export interface CodePromptTask {
  title: string
  description: string
  dueDate: string | null
  priority: string
}

export function codePromptRequest(task: CodePromptTask): string {
  return [
    `Задача: ${task.title}`,
    task.dueDate ? `Срок: ${task.dueDate}` : null,
    `Приоритет: ${task.priority}`,
    '',
    'Описание и подзадачи:',
    task.description.trim() || '(описания нет)'
  ]
    .filter((line) => line !== null)
    .join('\n')
}
